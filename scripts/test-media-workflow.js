import { mkdtemp, mkdir, writeFile, readFile, rm, copyFile, rename, access } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import assert from 'node:assert/strict';
import sharp from 'sharp';
import { prepareContent, validateFolder, hash } from './prepare-content.js';
import { checkArchive } from './archive-check.js';
import { renderContent } from './content.js';
const run = promisify(execFile);
const parent = await mkdtemp(path.join(tmpdir(),'leo-media-'));
const root = path.join(parent,'checkout');
const folder = 'incoming/photography/2026-11-14_La-Jolla';
const otherFolder = 'incoming/photography/Coastal';
const source = `${folder}/original.png`;
async function writeData(records) {
  for (const collection of ['events','art']) await writeFile(path.join(root,`content/${collection}.json`),'[]\n');
  await writeFile(path.join(root,'content/photography.json'),JSON.stringify(records,null,2)+'\n');
}
const photo = (id,image)=>({id,title:id,published:true,image,alt:id});
const git = args=>run('git',args,{cwd:root});
try {
  await mkdir(path.join(root,'content'),{recursive:true});
  await mkdir(path.join(root,folder),{recursive:true});
  await mkdir(path.join(root,otherFolder),{recursive:true});
  await sharp({create:{width:1800,height:2000,channels:3,background:'red'}}).png().toFile(path.join(root,source));
  await sharp({create:{width:100,height:80,channels:3,background:'blue'}}).png().toFile(path.join(root,otherFolder,'unselected.png'));
  const original = await readFile(path.join(root,source));
  const unselected = await readFile(path.join(root,otherFolder,'unselected.png'));
  validateFolder('incoming/events/2026-11-14_地点');
  validateFolder('incoming/art/作品名称');
  assert.throws(()=>validateFolder('incoming/events/2026-02-30_地点'));
  assert.throws(()=>validateFolder('incoming/photography'));
  assert.throws(()=>validateFolder('incoming/photography/../other'));
  await mkdir(path.join(root,'assets'),{recursive:true});
  await copyFile(path.join(root,source),path.join(root,'assets/legacy.png'));
  await writeData([photo('legacy','assets/legacy.png'),photo('candidate',source)]);
  await assert.rejects(prepareContent(root,{folder}),/Already processed image/,'Legacy website images must not be re-imported');
  await writeData([photo('first',source)]);
  await assert.rejects(prepareContent(root),/explicitly approved/);
  await assert.rejects(prepareContent(root,{folder:otherFolder}),/Outside selected folder/);
  await assert.rejects(access(path.join(root,'assets/uploads')));
  assert.equal(await prepareContent(root,{folder}),1);
  assert.deepEqual(await readFile(path.join(root,source)),original,'Original bytes must not change');
  assert.deepEqual(await readFile(path.join(root,otherFolder,'unselected.png')),unselected);
  let records=JSON.parse(await readFile(path.join(root,'content/photography.json')));
  const entry=JSON.parse(await readFile(path.join(root,'content/media-registry.json'))).images[0];
  assert.equal(entry.originalSha256,hash(original));
  assert.equal(entry.usages[0].id,'first');
  const meta=await sharp(path.join(root,entry.asset)).metadata();
  assert(meta.width<=1600 && meta.height<=1600 && !meta.exif);
  assert.equal(await prepareContent(root,{folder}),0);
  await copyFile(path.join(root,source),path.join(root,folder,'renamed.png'));
  await writeData([...records,photo('duplicate',`${folder}/renamed.png`)]);
  const before=await readFile(path.join(root,'content/photography.json'));
  await assert.rejects(prepareContent(root,{folder}),/Already processed image/);
  assert.deepEqual(await readFile(path.join(root,'content/photography.json')),before);
  assert.equal(await prepareContent(root,{folder,reuseExisting:true}),1);
  records=JSON.parse(await readFile(path.join(root,'content/photography.json')));
  assert.equal(records[0].image,records[1].image,'Approved reuse must share the same web asset');
  assert.equal(JSON.parse(await readFile(path.join(root,'content/media-registry.json'))).images.length,1);
  await writeData([photo('reimport',source)]);
  await assert.rejects(prepareContent(root,{folder}),/Already processed image/,'Deleted content must not erase import history');
  await writeData(records);
  // A real local Git remote simulates GitHub without any internet or live website changes.
  await git(['init','-b','review']);
  await git(['config','user.name','Workflow Test']);
  await git(['config','user.email','workflow@example.invalid']);
  await writeFile(path.join(root,'.gitignore'),'incoming/\n');
  await git(['add','.']); await git(['commit','-m','Prepare selected image']);
  await run('git',['init','--bare',path.join(parent,'remote.git')]);
  await git(['remote','add','origin',path.join(parent,'remote.git')]);
  await assert.rejects(checkArchive(root,{folder}),/./,'Unpushed content cannot pass archive check');
  await git(['push','-u','origin','review']);
  const result=await checkArchive(root,{folder});
  assert.equal(result.safeToArchive,true); assert.equal(result.verified.length,2);
  await access(path.join(root,source)); // audit never moved anything
  await writeFile(path.join(root,'content/photography.json'),'[]\n');
  await assert.rejects(checkArchive(root,{folder}),/differs from GitHub/);
  await writeData(records);
  const stored=await readFile(path.join(root,entry.asset));
  await writeFile(path.join(root,entry.asset),'changed');
  await assert.rejects(checkArchive(root,{folder}),/Local prepared asset changed/);
  await writeFile(path.join(root,entry.asset),stored);
  await copyFile(path.join(root,otherFolder,'unselected.png'),path.join(root,folder,'unprocessed.png'));
  await assert.rejects(checkArchive(root,{folder}),/Unprocessed file/);
  // Only disposable test fixtures are moved; never user originals.
  await rename(path.join(root,'incoming'),path.join(parent,'test-archive'));
  assert.equal(await prepareContent(root),0);
  const output=await renderContent(root,path.join(root,'dist'));
  assert(output.photography.includes('first'));
  assert(!output.photography.includes('incoming/'));
  console.log('Media workflow passed: explicit scope, original preservation, renamed duplicate blocking, approved reuse, remote verification, archive blockers, original-free rebuild.');
} finally { await rm(parent,{recursive:true,force:true}); }
